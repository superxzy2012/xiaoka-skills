#!/usr/bin/env python3
"""从 CDP 桥（BOSS 已登录的 Chrome）导出抖音 cookie 给 yt-dlp。

用 memories/cdp.py（websocket-client，suppress_origin），不用 playwright —
Storage.getCookies 必须不带 browserContextId 参数。
"""
import json
import os
import sys

sys.path.insert(0, "/opt/data/memories")
from cdp import CDP  # noqa: E402

OUT_DIR = "/opt/data/memories/cookies"
KEYS = ("sessionid", "sessionid_ss", "ttwid", "passport_csrf_token", "odin_tt", "s_v_web_id")


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    with CDP() as c:
        r = c.call("Storage.getCookies", {}, c._sid)
    raw = (r.get("result") or {}).get("cookies", [])
    sel = [k for k in raw if "douyin" in k.get("domain", "")]
    if not sel:
        raise SystemExit("0 cookie — BOSS 的 Chrome 里没有抖音登录态")

    with open(f"{OUT_DIR}/douyin.json", "w", encoding="utf-8") as f:
        json.dump(sel, f, ensure_ascii=False, indent=1)

    lines = ["# Netscape HTTP Cookie File", "# Generated by 小卡 from CDP bridge", ""]
    for k in sel:
        dom = k.get("domain", "")
        flag = "TRUE" if dom.startswith(".") else "FALSE"
        path = k.get("path", "/")
        secure = "TRUE" if k.get("secure") else "FALSE"
        exp = int(k.get("expires", 0) or 0)
        lines.append(f"{dom}\t{flag}\t{path}\t{secure}\t{exp}\t{k['name']}\t{k['value']}")
    with open(f"{OUT_DIR}/douyin_cookies.txt", "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    names = sorted(k["name"] for k in sel)
    print(f"导出 {len(sel)} 条 cookie")
    print("关键:", [n for n in names if n in KEYS])
    print("全部:", names)


if __name__ == "__main__":
    main()
